const AUTOGENERATED: &str = "<autogenerated>";

const CGO_GENERATED: [&str; 3] = ["_cgo_gotypes.go", "cgo-gcc-prolog", "_cgo_export.c"];

pub fn cgo_wrote(path: &std::path::Path) -> bool {
    path.file_name()
        .and_then(|name| name.to_str())
        .is_some_and(|name| CGO_GENERATED.contains(&name))
}

pub fn cgo_generated(functions: &[FunctionInfo], source_files: &[PathBuf]) -> Vec<bool> {
    declared_in(functions, source_files, cgo_wrote)
}

pub fn cgo_runtime(functions: &[FunctionInfo], source_files: &[PathBuf]) -> Vec<bool> {
    declared_in(functions, source_files, |path| {
        path.parent()
            .is_some_and(|directory| directory.ends_with("src/runtime/cgo"))
    })
}

fn declared_in(
    functions: &[FunctionInfo],
    source_files: &[PathBuf],
    file: impl Fn(&std::path::Path) -> bool,
) -> Vec<bool> {
    let in_file = source_files
        .iter()
        .map(|path| file(path))
        .collect::<Vec<_>>();

    functions
        .iter()
        .map(|function| {
            function
                .declaration
                .as_ref()
                .and_then(|location| in_file.get(location.file.index()))
                .is_some_and(|within| *within)
        })
        .collect()
}

pub fn function_role(name: &str, trampoline: bool) -> CodeRole {
    if trampoline {
        return CodeRole::Wrapper;
    }

    symbol_role(name)
}

pub fn rust_role(namespace: &str, name: &str) -> Option<CodeRole> {
    let within = |path: &str| {
        namespace
            .strip_prefix(path)
            .is_some_and(|rest| rest.is_empty() || rest.starts_with("::"))
    };

    let named = |function: &str| {
        name.strip_prefix(function)
            .is_some_and(|rest| rest.is_empty() || rest.starts_with('<'))
    };

    if within("std::panicking::catch_unwind")
        || (within("std::panicking") || within("std::panic")) && named("catch_unwind")
    {
        return Some(CodeRole::RuntimeInternal);
    }

    if within("core::panicking")
        || within("std::panicking")
        || within("__rustc")
        || (within("std::sys::backtrace") && named("__rust_end_short_backtrace"))
    {
        return Some(CodeRole::Panic);
    }

    if namespace == "tokio::runtime::task::harness" && name.starts_with("poll<") {
        return Some(CodeRole::Dispatch);
    }

    if within("tokio") || within("mio") {
        return Some(CodeRole::RuntimeInternal);
    }

    (within("core::future")
        || within("core::pin")
        || within("core::panic::unwind_safe")
        || (within("alloc::boxed") && (named("poll") || named("deref_mut")))
        || (within("core::ptr") && crate::rust_names::DROP_GLUE.iter().any(|glue| named(glue))))
    .then_some(CodeRole::Wrapper)
}

pub fn abi_wrappers(functions: &[FunctionInfo], source_files: &[PathBuf]) -> Vec<bool> {
    let generated = declared_in(functions, source_files, |path| {
        path.file_name().is_some_and(|file| file == AUTOGENERATED)
    });
    if !generated.contains(&true) {
        return generated;
    }

    let written = functions
        .iter()
        .zip(&generated)
        .filter(|(_, generated)| !**generated)
        .map(|(function, _)| &*function.name)
        .collect::<BTreeSet<_>>();
    functions
        .iter()
        .zip(generated)
        .map(|(function, generated)| generated && written.contains(&*function.name))
        .collect()
}

pub fn link_loop_bodies(functions: &mut [FunctionInfo]) {
    let mut by_name = std::collections::HashMap::new();
    for function in functions.iter().filter(|function| {
        function.language == SourceLanguage::Go && function.role != CodeRole::Wrapper
    }) {
        by_name.entry(function.name.clone()).or_insert(function.id);
    }

    for function in functions
        .iter_mut()
        .filter(|function| function.language == SourceLanguage::Go)
    {
        function.enclosing = go_loop_parent(&function.name)
            .and_then(|parent| by_name.get(parent))
            .copied();
    }
}

fn go_loop_parent(name: &str) -> Option<&str> {
    let (parent, number) = name.rsplit_once("-range")?;
    (!parent.is_empty() && !number.is_empty() && number.bytes().all(|byte| byte.is_ascii_digit()))
        .then_some(parent)
}

const ROLES: [(&str, CodeRole); 4] = [
    ("_start", CodeRole::Outermost),
    ("__restore_rt", CodeRole::SignalTrampoline),
    ("__rust_try", CodeRole::RuntimeInternal),
    ("py::jit:executor", CodeRole::Interpreter),
];

pub fn symbol_role(name: &str) -> CodeRole {
    if !ROLES.iter().any(|(role, _)| name.starts_with(role)) {
        return CodeRole::Ordinary;
    }

    let name = split_from(name);
    ROLES
        .iter()
        .find(|(role, _)| *role == name)
        .map_or(CodeRole::Ordinary, |(_, role)| *role)
}

