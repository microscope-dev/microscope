pub fn go_role(name: &str, facts: Option<GoFunctionFacts>, generated: bool) -> CodeRole {
    let special = facts.and_then(|facts| facts.special);
    if name == "runtime.sigreturn__sigaction" {
        return CodeRole::SignalTrampoline;
    }

    if matches!(
        special,
        Some(
            SpecialFunction::Sigpanic
                | SpecialFunction::AsyncPreempt
                | SpecialFunction::DebugCallV2
        )
    ) {
        return CodeRole::TrapEntry;
    }

    let signal_handler = matches!(name, "runtime.sigtramp" | "runtime.cgoSigtramp");
    if facts.is_some_and(|facts| facts.top_frame) && !signal_handler {
        return CodeRole::Outermost;
    }

    if facts.is_some_and(|facts| facts.sp_write)
        || matches!(
            special,
            Some(
                SpecialFunction::Systemstack
                    | SpecialFunction::Mcall
                    | SpecialFunction::Morestack
                    | SpecialFunction::AsmCgoCall
                    | SpecialFunction::CgoCallback
            )
        )
    {
        return CodeRole::StackSwitch;
    }

    if special == Some(SpecialFunction::Wrapper) || generated {
        return CodeRole::Wrapper;
    }

    if name == "runtime.gopanic" {
        return CodeRole::Panic;
    }

    if name == "runtime.execute" {
        return CodeRole::Dispatch;
    }

    if is_runtime_internal(name) {
        return CodeRole::RuntimeInternal;
    }

    CodeRole::Ordinary
}

fn is_runtime_internal(name: &str) -> bool {
    if name.starts_with("internal/runtime/") || name.starts_with("runtime/internal/") {
        return true;
    }

    if !name.contains('.') {
        return true;
    }

    name.strip_prefix("runtime.")
        .is_some_and(|rest| !is_exported_runtime(rest))
}

fn is_exported_runtime(name: &str) -> bool {
    let (receiver, function) = name.rsplit_once('.').unwrap_or(("", name));
    let receiver = receiver
        .strip_prefix("(*")
        .and_then(|receiver| receiver.strip_suffix(')'))
        .unwrap_or(receiver);
    let exported = |text: &str| text.starts_with(|first: char| first.is_ascii_uppercase());
    exported(function) && (receiver.is_empty() || exported(receiver))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn split_off_parts_and_copies_play_their_functions_role() {
        for name in [
            "_start.cold",
            "_start.cold.1",
            "_start.part.0",
            "_start.isra.0",
            "_start.constprop.3",
            "_start.lto_priv.0",
            "_start.isra.0.cold",
            "_start.constprop.0.isra.0.part.2",
        ] {
            assert_eq!(symbol_role(name), CodeRole::Outermost, "{name}");
        }

        assert_eq!(symbol_role("__restore_rt.cold"), CodeRole::SignalTrampoline);
    }

    #[test]
    fn cpythons_loop_and_call_machinery_are_the_interpreters() {
        for name in [
            "_PyEval_EvalFrameDefault",
            "_PyEval_EvalFrameDefault.cold",
            "cfunction_vectorcall_O",
            "method_vectorcall",
            "thread_run",
            "Py_RunMain",
            "_TAIL_CALL_CALL",
            "_TAIL_CALL_CALL_BUILTIN_FAST.warm",
            "PyGen_am_send.lto_priv.0",
        ] {
            assert_eq!(cpython_role(name), Some(CodeRole::Interpreter), "{name}");
        }

        for name in [
            "time_sleep",
            "pysleep",
            "builtin_exec",
            "main",
            "_PyEval_Vector2",
        ] {
            assert_eq!(cpython_role(name), None, "{name}");
        }

        assert_eq!(symbol_role("_PyEval_EvalFrameDefault"), CodeRole::Ordinary);
        assert_eq!(symbol_role("py::jit:executor"), CodeRole::Interpreter);
    }

    #[test]
    fn v8s_interpreter_entry_is_the_interpreters() {
        assert_eq!(
            v8_role("Builtins_InterpreterEntryTrampoline"),
            Some(CodeRole::Interpreter)
        );
        assert_eq!(
            v8_role("Builtins_InterpreterEntryTrampolineForProfiling"),
            Some(CodeRole::Interpreter)
        );
        for name in ["Builtins_AddHandler", "Builtins_JSEntry", "main"] {
            assert_eq!(v8_role(name), None, "{name}");
        }
        assert_eq!(
            symbol_role("Builtins_InterpreterEntryTrampoline"),
            CodeRole::Ordinary
        );
    }

    #[test]
    fn asyncios_task_stepping_is_the_interpreters() {
        for name in [
            "task_step",
            "task_step_impl.isra.0",
            "TaskStepMethWrapper_call",
        ] {
            assert_eq!(asyncio_role(name), Some(CodeRole::Interpreter), "{name}");
        }

        for name in ["future_set_result", "_asyncio_Future_result", "task_step_x"] {
            assert_eq!(asyncio_role(name), None, "{name}");
        }
    }

    #[test]
    fn other_dotted_names_are_functions_of_their_own() {
        for name in [
            "_start.1",
            "_start.hot",
            "_start.cold.x",
            ".cold",
            "cold",
            "_start.",
            "_start..cold",
        ] {
            assert_eq!(symbol_role(name), CodeRole::Ordinary, "{name}");
        }
    }
}
