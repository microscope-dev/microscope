//! Go's own function table, `.gopclntab`, which the runtime reads for its
//! tracebacks and which survives stripping.
//!
//! The table's layout is keyed by its magic number: only the format Go 1.20
//! through 1.27 write (`0xfffffff1`) is read, and every other magic is
//! refused with the releases that wrote it. Function IDs are numbered
//! differently across those releases, so they are interpreted only for the
//! releases whose numbering is written down here, by the Go version the
//! image records. Every read is bounded, and a malformed table is a typed
//! error, never a guess.

mod metadata;
mod unwind;

pub use metadata::{Catalog, complete as complete_metadata};
pub use unwind::{GoUnwind, frame_saves};

use crate::image::unwind::GoTableFacts;
use std::ops::Range;
use std::sync::Arc;

/// The magic number of the table Go 1.20 through 1.27 write.
const GO120_MAGIC: u32 = 0xffff_fff1;

/// The size of the table header: the magic, two pad bytes, the instruction
/// size quantum, the pointer size, and eight pointer-sized words.
const HEADER_SIZE: usize = 8 + 8 * 8;

/// The fixed part of one function's `_func` record, before its `pcdata`
/// and `funcdata` offsets.
const FUNC_SIZE: usize = 44;

/// The size of one inline-tree entry, an `inlinedCall`.
const INLINED_CALL_SIZE: usize = 16;

/// `PCDATA_UnsafePoint`, the pc-value table saying where the runtime may
/// preempt a goroutine asynchronously, and where it then resumes it.
const PCDATA_UNSAFE_POINT: usize = 0;

/// `PCDATA_InlTreeIndex`, the pc-value table giving the inline-tree entry
/// at each instruction.
const PCDATA_INLINE_TREE_INDEX: usize = 2;

/// `FUNCDATA_InlTree`, the offset of a function's inline tree from
/// `go:func.*`.
const FUNCDATA_INLINE_TREE: usize = 3;

/// `abi.FuncFlagTopFrame`: the function is the outermost frame of a stack.
const FLAG_TOP_FRAME: u8 = 1 << 0;

/// `abi.FuncFlagSPWrite`: the function writes SP other than by a constant.
const FLAG_SP_WRITE: u8 = 1 << 1;

/// `abi.FuncFlagAsm`: the function is written in assembly.
const FLAG_ASM: u8 = 1 << 2;

/// The longest pc-value delta a well-formed table encodes, in varint bytes.
const MAX_VARINT_BYTES: usize = 5;

/// Why a Go function table cannot be read.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum PclntabError {
    #[error("the Go function table is truncated: {0}")]
    Truncated(&'static str),

    #[error("the Go function table was written by {0}, whose format is not supported")]
    UnsupportedRelease(&'static str),

    #[error("the Go function table's magic number {0:#010x} is unknown")]
    UnknownMagic(u32),

    #[error("the Go function table is malformed: {0}")]
    Malformed(Arc<str>),

    #[error("the Go function table's code addresses are relative to an unknown text start")]
    TextStartUnknown,
}

type Result<T> = std::result::Result<T, PclntabError>;

fn malformed(reason: impl Into<Arc<str>>) -> PclntabError {
    PclntabError::Malformed(reason.into())
}

/// A function the runtime treats specially, by its function ID.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SpecialFunction {
    Abort,
    AsmCgoCall,
    AsyncPreempt,
    CgoCallback,
    CoroStart,
    DebugCallV2,
    GcBgMarkWorker,
    Goexit,
    Gogo,
    Gopanic,
    HandleAsyncEvent,
    Mcall,
    Morestack,
    Mstart,
    Panicwrap,
    Rt0Go,
    RuntimeMain,
    RunFinalizers,
    RunCleanups,
    Sigpanic,
    Systemstack,
    SystemstackSwitch,

    /// Autogenerated code: ABI and method wrappers, hash and equality
    /// algorithms, and the like.
    Wrapper,
}

/// How a release numbers its function IDs (`internal/abi.FuncID`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum FuncIdNumbering {
    /// Go 1.25 through 1.27, which added `runFinalizers` and `runCleanups`
    /// in place of `runfinq`.
    Go125,
}

impl FuncIdNumbering {
    /// The numbering of a release, for the releases written down here.
    const fn of(release: GoRelease) -> Option<Self> {
        match release {
            GoRelease {
                major: 1,
                minor: 25..=27,
            } => Some(Self::Go125),
            _ => None,
        }
    }

    const fn special(self, id: u8) -> Option<SpecialFunction> {
        use SpecialFunction as S;
        match self {
            Self::Go125 => Some(match id {
                1 => S::Abort,
                2 => S::AsmCgoCall,
                3 => S::AsyncPreempt,
                4 => S::CgoCallback,
                5 => S::CoroStart,
                6 => S::DebugCallV2,
                7 => S::GcBgMarkWorker,
                8 => S::Goexit,
                9 => S::Gogo,
                10 => S::Gopanic,
                11 => S::HandleAsyncEvent,
                12 => S::Mcall,
                13 => S::Morestack,
                14 => S::Mstart,
                15 => S::Panicwrap,
                16 => S::Rt0Go,
                17 => S::RuntimeMain,
                18 => S::RunFinalizers,
                19 => S::RunCleanups,
                20 => S::Sigpanic,
                21 => S::Systemstack,
                22 => S::SystemstackSwitch,
                23 => S::Wrapper,
                _ => return None,
            }),
        }
    }
}

/// A Go release, as `runtime.buildVersion` names it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct GoRelease {
    pub major: u32,
    pub minor: u32,
}

impl GoRelease {
    /// Parses a version such as `go1.27.1` or `go1.27rc1`; a development
    /// build names no release.
    fn parse(version: &str) -> Option<Self> {
        let rest = version.strip_prefix("go")?;
        let mut parts = rest.split('.');
        let major = parts.next()?.parse().ok()?;
        let minor = parts.next()?;
        let digits = minor
            .find(|character: char| !character.is_ascii_digit())
            .unwrap_or(minor.len());
        Some(Self {
            major,
            minor: minor[..digits].parse().ok()?,
        })
    }
}

