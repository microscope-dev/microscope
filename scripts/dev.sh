#!/usr/bin/env bash




set -euo pipefail

keep=(
    HOME USER LOGNAME TERM COLORTERM NO_COLOR CLICOLOR CLICOLOR_FORCE

    XDG_RUNTIME_DIR DBUS_SESSION_BUS_ADDRESS
    CARGO_HOME CARGO_TARGET_DIR RUST_BACKTRACE RUST_LOG

    MICROSCOPE_CACHE_DIR MICROSCOPE_CONFIG MICROSCOPE_FIXTURE_JOBS MICROSCOPE_FLIGHT_RECORDING
    MICROSCOPE_JOBS MICROSCOPE_MEMORY_MAX MICROSCOPE_UPDATE_PROTOCOL MICROSCOPE_UPDATE_SYSCALLS
    MICROSCOPE_UPDATE_V8
    MICROSCOPE_WEB_BINARY MICROSCOPE_WEB_TRANSCRIPTS MICROSCOPE_SERVICES_BINARY DATABASE_URL
    STORAGE_BUCKET STORAGE_ENDPOINT STORAGE_ACCESS_KEY STORAGE_SECRET_KEY STORAGE_PREFIX

    MICROSCOPE_SWARM_STEPS MICROSCOPE_SWARM_SEED MICROSCOPE_TEST_BUDGET_SCALE

    NEXTEST_PROFILE

    PROPTEST_CASES PROPTEST_MAX_SHRINK_ITERS PROPTEST_MAX_SHRINK_TIME
    PROPTEST_RNG_SEED PROPTEST_TIMEOUT PROPTEST_VERBOSE

    MICROSCOPE_HERMETIC
)
export MICROSCOPE_HERMETIC=1
arguments=()
for name in "${keep[@]}"; do
    arguments+=(--keep "$name")
done
exec nix --extra-experimental-features 'nix-command flakes' develop --ignore-env \
    "${arguments[@]}" "$@"
