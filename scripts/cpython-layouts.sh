#!/usr/bin/env bash
# Compiles scripts/cpython-layouts.c against each CPython interpreter's headers
# in $MICROSCOPE_CPYTHON and writes the Rust layout table. Usage:
#   scripts/cpython-layouts.sh [OUTPUT]

set -euo pipefail

if [[ -z "${MICROSCOPE_CPYTHON:-}" ]]; then
    echo "MICROSCOPE_CPYTHON is not set; run this inside 'just dev'" >&2
    exit 1
fi

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
output="${1:-$root/src/debug_info/cpython/layouts.gen.rs}"
source_file="$root/scripts/cpython-layouts.c"

shopt -s nullglob
mapfile -t dirs < <(printf '%s\n' "$MICROSCOPE_CPYTHON"/*/ | LC_ALL=C sort)
if [[ ${#dirs[@]} -eq 0 ]]; then
    echo "no interpreter directories under $MICROSCOPE_CPYTHON" >&2
    exit 1
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

entries="$tmp/entries.rs"
: > "$entries"

for dir in "${dirs[@]}"; do
    dir="${dir%/}"
    name="$(basename "$dir")"

    includes=()
    if [[ -d "$dir/include-arch" ]]; then
        includes+=("-I$dir/include-arch")
    fi
    includes+=("-I$dir/include")

    bin="$tmp/layouts-$name"
    cc -std=c11 -O0 -w -DPy_BUILD_CORE=1 "${includes[@]}" "$source_file" -o "$bin"
    "$bin" "$name" >> "$entries"
done

mkdir -p "$(dirname "$output")"
{
    cat <<'EOF'
// @generated by scripts/cpython-layouts.sh from each interpreter's headers. Do not edit.

use super::Generated;
use crate::image::python::{Constant, Field};

pub(super) const GENERATED: &[Generated] = &[
EOF
    cat "$entries"
    cat <<'EOF'
];
EOF
} > "$tmp/layouts.rs"

mv "$tmp/layouts.rs" "$output"
echo "wrote $output (${#dirs[@]} interpreters)"
