#!/usr/bin/env bash
# Writes the Rust table of code points unprintable in every $MICROSCOPE_CPYTHON
# interpreter's Unicode database, as reported by str.isprintable. Usage:
#   scripts/python-printable.sh [OUTPUT]

set -euo pipefail

if [[ -z "${MICROSCOPE_CPYTHON:-}" ]]; then
    echo "MICROSCOPE_CPYTHON is not set; run this inside 'just dev'" >&2
    exit 1
fi

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
output="${1:-$root/src/runtime_model/python/printable.gen.rs}"

shopt -s nullglob
mapfile -t dirs < <(printf '%s\n' "$MICROSCOPE_CPYTHON"/*/ | LC_ALL=C sort)
if [[ ${#dirs[@]} -eq 0 ]]; then
    echo "no interpreter directories under $MICROSCOPE_CPYTHON" >&2
    exit 1
fi

# Each interpreter's unprintable code points, as a byte per code point.
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
tables=()
for dir in "${dirs[@]}"; do
    table="$tmp/$(basename "$dir")"
    "${dir%/}/python" -I -c '
import sys
sys.stdout.buffer.write(bytes(not chr(point).isprintable() for point in range(0x110000)))
' > "$table"
    tables+=("$table")
done

"${dirs[0]%/}/python" -I - "$output" "${tables[@]}" <<'PY'
import sys

output, *tables = sys.argv[1:]
everywhere = None
for path in tables:
    with open(path, 'rb') as file:
        table = file.read()
    everywhere = table if everywhere is None else bytes(
        a & b for a, b in zip(everywhere, table))
ranges = []
start = None
for point, escaped in enumerate(everywhere):
    if escaped and start is None:
        start = point
    elif not escaped and start is not None:
        ranges.append((start, point))
        start = None
if start is not None:
    ranges.append((start, len(everywhere)))
with open(output, 'w') as file:
    file.write(
        "// @generated by scripts/python-printable.sh from each interpreter's\n"
        "// str.isprintable. Do not edit.\n"
        "#![allow(\n"
        "    clippy::unreadable_literal,\n"
        "    reason = \"generated code points, written as Unicode writes them\"\n"
        ")]\n"
        "\n"
        "/// The code points every interpreter in the matrix escapes in a `str`'s\n"
        "/// `repr`, as ranges from a first to past a last, in order.\n"
        f"pub(super) const ESCAPED: [(u32, u32); {len(ranges)}] = [\n")
    for first, past in ranges:
        file.write(f"    (0x{first:06x}, 0x{past:06x}),\n")
    file.write("];\n")
print(f"wrote {output} ({len(tables)} interpreters, {len(ranges)} ranges)")
PY
